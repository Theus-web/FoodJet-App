// ============================================================
// EXECUÇÃO PRINCIPAL
// ============================================================

async function migrar() {

    let client;

    try {

        console.log("");
        console.log("============================================");
        console.log("🚀 ATUALIZAÇÃO ESTRUTURAL FOODJET");
        console.log("============================================");

        console.log(
            "🐘 PostgreSQL será usado como fonte de dados."
        );

        console.log(
            "🚫 foodjet.json não será utilizado."
        );

        console.log("");

        // ====================================================
        // CONECTAR
        // ====================================================

        client =
            await pool.connect();

        await verificarConexao(
            client
        );

        // ====================================================
        // INICIAR TRANSAÇÃO
        // ====================================================

        await client.query(
            "BEGIN"
        );

        // ====================================================
        // CRIAR / VERIFICAR ESTRUTURA
        // ====================================================

        await criarEstrutura(
            client
        );

        // ====================================================
        // GARANTIR CARTEIRAS
        // ====================================================

        await garantirCarteiras(
            client
        );

        // ====================================================
        // COMMIT
        // ====================================================

        await client.query(
            "COMMIT"
        );

        console.log("");
        console.log("============================================");
        console.log("✅ ALTERAÇÕES CONFIRMADAS");
        console.log("============================================");

        // ====================================================
        // RESUMO
        // ====================================================

        await mostrarResumo(
            client
        );

        console.log("");
        console.log("============================================");
        console.log("🎉 ESTRUTURA FOODJET ATUALIZADA!");
        console.log("============================================");

    } catch (error) {

        if (client) {

            try {

                await client.query(
                    "ROLLBACK"
                );

                console.log(
                    "↩️ ROLLBACK executado."
                );

            } catch (rollbackError) {

                console.error(
                    "❌ Erro no ROLLBACK:",
                    rollbackError.message
                );
            }
        }

        console.error("");
        console.error(
            "❌ ERRO DURANTE A ATUALIZAÇÃO:"
        );

        console.error(
            error.message
        );

        console.error("");

        process.exitCode = 1;

    } finally {

        if (client) {
            client.release();
        }

        await pool.end();
    }
}

// ============================================================
// EXECUTAR
// ============================================================

migrar();

